    foreach ($statements as $statement) {
        $pdo->exec($statement);
    }
    $pdo->exec('INSERT OR IGNORE INTO schema_migrations (version) VALUES (1)');

    // Versão 2: ficha completa do fornecedor (endereço, telefone, responsável, observações...)
    $supplierColumns = array_column($pdo->query('PRAGMA table_info(suppliers_rel)')->fetchAll(PDO::FETCH_ASSOC), 'name');
    if (!in_array('atributos_json', $supplierColumns, true)) {
        $pdo->exec("ALTER TABLE suppliers_rel ADD COLUMN atributos_json TEXT NOT NULL DEFAULT '{}'");
    }
    $pdo->exec('INSERT OR IGNORE INTO schema_migrations (version) VALUES (2)');

    // Versão 3 (área do consultor) depende de users e leads, criadas em schema.php
    $baseTables = $pdo->query("SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name IN ('users', 'leads')")->fetchColumn();
    if ((int)$baseTables === 2 && function_exists('createConsultorSchema')) {
        createConsultorSchema($pdo);
    }
}
