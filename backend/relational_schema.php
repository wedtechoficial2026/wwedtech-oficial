            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS business_notifications (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            tipo TEXT NOT NULL,
            mensagem TEXT NOT NULL,
            rota TEXT NOT NULL DEFAULT '',
            lida INTEGER NOT NULL DEFAULT 0 CHECK (lida IN (0, 1)),
            criado_em INTEGER,
            UNIQUE (business_id, legacy_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS automation_logs (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            regra TEXT NOT NULL,
            mensagem TEXT NOT NULL,
            criado_em INTEGER,
            UNIQUE (business_id, legacy_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS inventory_scans (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            tipo TEXT NOT NULL,
            sku TEXT NOT NULL DEFAULT '',
            produto TEXT NOT NULL DEFAULT '',
            local TEXT NOT NULL DEFAULT '',
            lido_em INTEGER,
            UNIQUE (business_id, legacy_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS inventory_losses (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            product_id INTEGER,
            motivo TEXT NOT NULL DEFAULT '',
            quantidade INTEGER NOT NULL DEFAULT 0,
            valor REAL NOT NULL DEFAULT 0 CHECK (valor >= 0),
            ocorrido_em INTEGER,
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE,
            FOREIGN KEY (product_id) REFERENCES products_rel(id) ON DELETE SET NULL,
            UNIQUE (business_id, legacy_id)
        )",
        "CREATE TABLE IF NOT EXISTS store_credits (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            codigo TEXT NOT NULL,
            cliente TEXT NOT NULL DEFAULT '',
            order_legacy_id TEXT NOT NULL DEFAULT '',
            valor_inicial REAL NOT NULL CHECK (valor_inicial >= 0),
            saldo REAL NOT NULL CHECK (saldo >= 0),
            criado_em INTEGER,
            UNIQUE (business_id, codigo),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS seasonal_events (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            nome TEXT NOT NULL,
            data_evento TEXT NOT NULL DEFAULT '',
            multiplicador REAL NOT NULL DEFAULT 1,
            dias_janela INTEGER NOT NULL DEFAULT 1,
            atributos_json TEXT NOT NULL DEFAULT '{}',
            UNIQUE (business_id, legacy_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS seasonal_reports (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            nome TEXT NOT NULL,
            dados_json TEXT NOT NULL,
            UNIQUE (business_id, legacy_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS business_preferences (
            business_id INTEGER NOT NULL,
            chave TEXT NOT NULL,
            valor TEXT NOT NULL,
            tipo_valor TEXT NOT NULL DEFAULT 'string',
            atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (business_id, chave),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS relational_sync_state (
            business_id INTEGER NOT NULL,
            origem TEXT NOT NULL,
            revision INTEGER NOT NULL,
            atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (business_id, origem),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
