            total REAL NOT NULL DEFAULT 0 CHECK (total >= 0),
            frete REAL NOT NULL DEFAULT 0 CHECK (frete >= 0),
            status TEXT NOT NULL,
            metodo_pagamento TEXT NOT NULL DEFAULT '',
            loja_retirada_id INTEGER,
            marketplace_demo TEXT NOT NULL DEFAULT '',
            dados_adicionais_json TEXT NOT NULL DEFAULT '{}',
            ocorrido_em INTEGER NOT NULL,
            atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
            UNIQUE (business_id, legacy_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE,
            FOREIGN KEY (loja_retirada_id) REFERENCES store_locations(id) ON DELETE SET NULL
        )",
        "CREATE TABLE IF NOT EXISTS order_items_rel (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            order_id INTEGER NOT NULL,
            product_id INTEGER,
            variant_id INTEGER,
            location_id INTEGER,
            sku_snapshot TEXT NOT NULL DEFAULT '',
            nome_snapshot TEXT NOT NULL,
            quantidade INTEGER NOT NULL CHECK (quantidade > 0),
            preco_unitario REAL NOT NULL CHECK (preco_unitario >= 0),
            bipado INTEGER NOT NULL DEFAULT 0 CHECK (bipado IN (0, 1)),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE,
            FOREIGN KEY (order_id) REFERENCES orders_rel(id) ON DELETE CASCADE,
            FOREIGN KEY (product_id) REFERENCES products_rel(id) ON DELETE SET NULL,
            FOREIGN KEY (variant_id) REFERENCES product_variants_rel(id) ON DELETE SET NULL,
            FOREIGN KEY (location_id) REFERENCES store_locations(id) ON DELETE SET NULL
        )",
        "CREATE TABLE IF NOT EXISTS order_returns (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            order_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            tipo TEXT NOT NULL,
            motivo TEXT NOT NULL DEFAULT '',
            valor REAL NOT NULL DEFAULT 0 CHECK (valor >= 0),
            credito_codigo TEXT NOT NULL DEFAULT '',
            ocorrido_em INTEGER NOT NULL,
            UNIQUE (business_id, order_id, legacy_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE,
            FOREIGN KEY (order_id) REFERENCES orders_rel(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS order_return_items (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            return_id INTEGER NOT NULL,
            order_item_index INTEGER NOT NULL DEFAULT 0,
            product_id INTEGER,
            variant_id INTEGER,
            quantidade INTEGER NOT NULL CHECK (quantidade > 0),
            valor_unitario REAL NOT NULL DEFAULT 0 CHECK (valor_unitario >= 0),
            voltou_estoque INTEGER NOT NULL DEFAULT 0 CHECK (voltou_estoque IN (0, 1)),
            custo_total REAL NOT NULL DEFAULT 0 CHECK (custo_total >= 0),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE,
            FOREIGN KEY (return_id) REFERENCES order_returns(id) ON DELETE CASCADE,
            FOREIGN KEY (product_id) REFERENCES products_rel(id) ON DELETE SET NULL,
            FOREIGN KEY (variant_id) REFERENCES product_variants_rel(id) ON DELETE SET NULL
        )",
        "CREATE TABLE IF NOT EXISTS stock_reservations (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            order_item_id INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            variant_id INTEGER,
            location_id INTEGER,
            quantidade INTEGER NOT NULL CHECK (quantidade > 0),
            status TEXT NOT NULL,
            criado_em INTEGER NOT NULL,
            UNIQUE (business_id, order_item_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE,
            FOREIGN KEY (order_item_id) REFERENCES order_items_rel(id) ON DELETE CASCADE,
            FOREIGN KEY (product_id) REFERENCES products_rel(id) ON DELETE CASCADE,
            FOREIGN KEY (variant_id) REFERENCES product_variants_rel(id) ON DELETE SET NULL,
            FOREIGN KEY (location_id) REFERENCES store_locations(id) ON DELETE SET NULL
        )",
        "CREATE TABLE IF NOT EXISTS purchase_orders_rel (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            supplier_id INTEGER,
            status TEXT NOT NULL,
            origem_automacao INTEGER NOT NULL DEFAULT 0 CHECK (origem_automacao IN (0, 1)),
            motivo TEXT NOT NULL DEFAULT '',
            criado_em INTEGER NOT NULL,
            enviado_em INTEGER,
            previsao_entrega_em INTEGER,
            atributos_json TEXT NOT NULL DEFAULT '{}',
            UNIQUE (business_id, legacy_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE,
            FOREIGN KEY (supplier_id) REFERENCES suppliers_rel(id) ON DELETE SET NULL
        )",
        "CREATE TABLE IF NOT EXISTS purchase_order_items_rel (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            purchase_order_id INTEGER NOT NULL,
            product_id INTEGER,
            sku_snapshot TEXT NOT NULL DEFAULT '',
            nome_snapshot TEXT NOT NULL,
            quantidade INTEGER NOT NULL CHECK (quantidade > 0),
            recebida INTEGER NOT NULL DEFAULT 0 CHECK (recebida >= 0),
            custo_unitario REAL NOT NULL DEFAULT 0 CHECK (custo_unitario >= 0),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE,
            FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders_rel(id) ON DELETE CASCADE,
            FOREIGN KEY (product_id) REFERENCES products_rel(id) ON DELETE SET NULL
        )",
        "CREATE TABLE IF NOT EXISTS expenses_rel (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            categoria TEXT NOT NULL,
            descricao TEXT NOT NULL,
            valor REAL NOT NULL CHECK (valor >= 0),
            data_texto TEXT NOT NULL DEFAULT '',
            ocorrido_em INTEGER,
            UNIQUE (business_id, legacy_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS invoices_rel (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            order_legacy_id TEXT NOT NULL DEFAULT '',
            channel TEXT NOT NULL DEFAULT '',
            chave TEXT NOT NULL DEFAULT '',
            total REAL NOT NULL DEFAULT 0 CHECK (total >= 0),
            emitida_em INTEGER,
            UNIQUE (business_id, legacy_id),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS invoice_items_rel (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            invoice_id INTEGER NOT NULL,
            sku_snapshot TEXT NOT NULL DEFAULT '',
            nome_snapshot TEXT NOT NULL,
            quantidade INTEGER NOT NULL CHECK (quantidade > 0),
            preco_unitario REAL NOT NULL CHECK (preco_unitario >= 0),
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE,
            FOREIGN KEY (invoice_id) REFERENCES invoices_rel(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS shipping_labels_rel (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
