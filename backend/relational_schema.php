            FOREIGN KEY (product_id) REFERENCES products_rel(id) ON DELETE CASCADE
        )",
        "CREATE TABLE IF NOT EXISTS electronic_labels (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            product_id INTEGER NOT NULL,
            preco REAL NOT NULL CHECK (preco >= 0),
            percentual_promocao REAL NOT NULL DEFAULT 0,
            desatualizada INTEGER NOT NULL DEFAULT 0 CHECK (desatualizada IN (0, 1)),
            sincronizada_em INTEGER,
            FOREIGN KEY (business_id) REFERENCES businesses(id) ON DELETE CASCADE,
            FOREIGN KEY (product_id) REFERENCES products_rel(id) ON DELETE CASCADE,
            UNIQUE (business_id, product_id)
        )",
        "CREATE TABLE IF NOT EXISTS orders_rel (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            business_id INTEGER NOT NULL,
            legacy_id TEXT NOT NULL,
            channel TEXT NOT NULL,
            tipo TEXT NOT NULL,
