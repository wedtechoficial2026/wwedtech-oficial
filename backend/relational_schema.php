        'CREATE INDEX IF NOT EXISTS idx_products_business_active ON products_rel (business_id, ativo, nome)',
        'CREATE INDEX IF NOT EXISTS idx_orders_business_time ON orders_rel (business_id, ocorrido_em DESC)',
        'CREATE INDEX IF NOT EXISTS idx_orders_business_channel_status ON orders_rel (business_id, channel, status)',
